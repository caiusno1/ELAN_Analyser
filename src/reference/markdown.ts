import { METHODS, NEW_QUESTIONS, STATISTICS, USE_CASES, VIEW_NAME } from "./content.ts";
import { REFERENCES, shortCitation } from "./references.ts";

const cite = (ids: string[] | undefined) => (ids && ids.length ? `\n\n*${ids.map(shortCitation).join(" · ")}*` : "");

/** docs/METHODS.md: the text of the Methods page as one Markdown document. */
export function methodsMarkdown(): string {
  const out: string[] = [];
  const p = (...lines: string[]) => out.push(...lines, "");

  p("# Methods and use cases", "<!-- Generated by scripts/write-docs.ts from src/reference. Edit the source, then run `npm run docs`. -->");
  p(
    "This document describes what ELAN Analyser computes and what it can be used for. The same text is available inside the program on the **Methods** page.",
    "",
    "- [Questions from the literature](#questions-from-the-literature)",
    "- [Questions that become possible](#questions-that-become-possible)",
    "- [How each analysis works](#how-each-analysis-works)",
    "- [Statistics](#statistics)",
    "- [References](#references)",
  );

  p("## Questions from the literature");
  p("What researchers have asked of time-aligned annotations of talk, gesture and gaze — and where each analysis is found in the program. Every result table can be taken to the statistics lab for inference across speakers and recordings.");
  for (const u of USE_CASES) {
    p(`### ${u.question}`);
    p(u.literature);
    p(`**In the program** (${VIEW_NAME[u.view]}). ${u.here}${cite(u.refs)}`);
  }

  p("## Questions that become possible");
  p(
    "These analyses are rarely published — not because the questions are uninteresting, but because each needs several tools and custom scripts in between: tiers have to be combined, events linked across modalities, chance levels simulated, and the nesting of annotations in speakers and recordings modelled. In the program the pieces are connected, so each one is a short recipe. They are suggestions for analyses, not established findings.",
  );
  for (const q of NEW_QUESTIONS) {
    p(`### ${q.title}`);
    p(q.why);
    p(...q.steps.map((s, i) => `${i + 1}. ${s}`));
    if (q.refs?.length) p(`*${q.refs.map(shortCitation).join(" · ")}*`);
  }

  p("## How each analysis works");
  for (const m of METHODS) {
    p(`### ${m.title}`);
    p(m.summary);
    p(...m.points.map((pt) => `- ${pt}`));
    if (m.caveat) p(`> ${m.caveat}`);
    if (m.refs.length) p(`*${m.refs.map(shortCitation).join(" · ")}*`);
  }

  p("## Statistics");
  for (const t of STATISTICS) {
    p(`### ${t.title}`);
    for (const para of t.paragraphs) p(para);
    if (t.refs.length) p(`*${t.refs.map(shortCitation).join(" · ")}*`);
  }

  p("## References");
  p(...REFERENCES.map((r) => `- ${r.text}`));
  p("ELAN is developed by the Max Planck Institute for Psycholinguistics, The Language Archive, Nijmegen. ELAN Analyser is an independent project and is not affiliated with or endorsed by the institute.");
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}
